"""Result payloads returned from the search orchestrator."""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field


class SearchResult(BaseModel):
    """Single result entry returned to the caller."""

    title: str = Field(default="", description="Human readable title")
    url: str | None = Field(default=None, description="Canonical URL for the resource")
    snippet: str | None = Field(
        default=None, description="Short textual snippet summarising the result"
    )
    score: float = Field(default=0.0, description="Normalized relevance score")
    provider: str = Field(description="Provider identifier that produced the result")
    raw_content: str | None = Field(
        default=None, description="Optional raw body content"
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict, description="Arbitrary provider metadata"
    )


class ProviderResult(BaseModel):
    """Provider level response used for observability and metrics."""

    provider: str = Field(description="Provider identifier")
    latency_ms: float = Field(ge=0.0, description="Execution latency in milliseconds")
    results: list[SearchResult] = Field(
        default_factory=list, description="Results generated by the provider"
    )
    cached: bool = Field(
        default=False, description="Whether the response was served from cache"
    )


class CombinedSearchResponse(BaseModel):
    """Aggregated response returned by the FastMCP tool."""

    results: list[SearchResult] = Field(
        default_factory=list, description="Merged and deduplicated search results"
    )
    providers: list[ProviderResult] = Field(
        default_factory=list, description="Per-provider result breakdown"
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict, description="Diagnostic metadata for the caller"
    )


__all__ = ["CombinedSearchResponse", "ProviderResult", "SearchResult"]
